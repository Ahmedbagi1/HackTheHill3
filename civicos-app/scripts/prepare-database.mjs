import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const env = loadEnv('production', projectRoot, 'VITE_AUTH0_');
// Match Vite's precedence for variables supplied by the shell/build environment.
const domain = (process.env.VITE_AUTH0_DOMAIN ?? env.VITE_AUTH0_DOMAIN ?? '').trim();
const clientId = (process.env.VITE_AUTH0_CLIENT_ID ?? env.VITE_AUTH0_CLIENT_ID ?? '').trim();
if (!/^(?:[a-z\d](?:[a-z\d-]*[a-z\d])?\.)+[a-z]{2,}$/i.test(domain)
    || domain.startsWith('your-')
    || !/^[a-z\d_-]+$/i.test(clientId) || clientId.startsWith('your-')) {
  throw new Error('Set the real VITE_AUTH0_DOMAIN and VITE_AUTH0_CLIENT_ID in .env.local first.');
}

const migration = await readFile(new URL('../supabase/migrations/202609260001_application_foundation.sql', import.meta.url), 'utf8');
const literal = (value) => `'${value.replaceAll("'", "''")}'`;
const sql = `-- Generated by npm run db:prepare. Review, then run the entire file in Supabase SQL Editor.
-- Contains only schema and public Auth0 configuration; no application data or secrets.
-- First-time setup only. If CivicOS tables already exist, STOP and report the error.
begin;

${migration}

insert into civicos_private.auth_configuration (issuer, client_id)
values (${literal(`https://${domain}/`)}, ${literal(clientId)});

commit;
notify pgrst, 'reload schema';

-- Expected final result: all three values true.
select
  (select relrowsecurity from pg_class where oid = 'public.applications'::regclass) as applications_rls,
  (select relrowsecurity from pg_class where oid = 'public.application_events'::regclass) as history_rls,
  exists (select 1 from civicos_private.auth_configuration where singleton) as auth0_configured;
`;

await writeFile(new URL('../supabase/setup.local.sql', import.meta.url), sql, { mode: 0o600 });
console.log('Prepared supabase/setup.local.sql using the configured public Auth0 identifiers.');
console.log('Nothing was sent to Supabase. Review the file and follow docs/PERSISTENCE.md.');
